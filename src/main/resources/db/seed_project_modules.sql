-- ---------------------------------------------------------------------
-- 验收
-- ---------------------------------------------------------------------
SELECT
    (SELECT COUNT(*) FROM project_modules WHERE parent_id IS NULL) AS 功能域_应为12,
    (SELECT COUNT(*) FROM project_modules WHERE parent_id IS NOT NULL) AS 模块_应为56,
    (SELECT COUNT(*) FROM module_tag_legacy_map) AS 标签映射_应为101;

-- 每个功能域下挂了多少元素（沿映射统计，验证归并是否均衡）
SELECT d.name AS 功能域,
       COUNT(DISTINCT m.id) AS 模块数,
       (SELECT COUNT(*) FROM ui_elements e
         JOIN module_tag_legacy_map x ON x.legacy_tag = e.module_tag
         JOIN project_modules c ON c.id = x.module_id
        WHERE c.parent_id = d.id) AS 元素数
FROM project_modules d
LEFT JOIN project_modules m ON m.parent_id = d.id
WHERE d.parent_id IS NULL
GROUP BY d.id, d.name, d.sort_order
ORDER BY d.sort_order;

-- 没能映射上的标签（应只剩 inspector 与空值）
SELECT IFNULL(e.module_tag, '(空)') AS 未映射标签, COUNT(*) AS 元素数
FROM ui_elements e
LEFT JOIN module_tag_legacy_map x ON x.legacy_tag = e.module_tag
WHERE x.legacy_tag IS NULL
GROUP BY e.module_tag ORDER BY 元素数 DESC;


